# #1212 — EMG filter sampling-rate awareness of the REAL upstream filter
# ---------------------------------------------------------------------------

def real_emg_fs_awareness() -> CheckResult:
    """Real nk.signal_filter / nk.emg_amplitude at fs=4000 vs assumed 1 kHz.

    A 900 Hz tone must be attenuated by the real filter at the true fs
    (intended band 10-400 Hz) and must pass through when the caller
    assumes 1 kHz (effective band 40-1600 Hz) — the #1212 failure class,
    measured against the real upstream functions.
    """
    nk_ = _need_nk()
    import numpy as np

    fs = 4000
    t = np.arange(0, 5, 1 / fs)
    emg = nk_.emg_simulate(duration=5, sampling_rate=fs, burst_number=3,
                           random_state=42)
    mixed = emg + 0.5 * np.sin(2 * np.pi * 900 * t) + 0.5 * np.sin(2 * np.pi * 100 * t)

    def band_energy(x, lo, hi):
        f = np.fft.rfftfreq(len(x), 1 / fs)
        power = np.abs(np.fft.rfft(x)) ** 2
        return float(power[(f >= lo) & (f < hi)].sum())

    raw_900 = band_energy(mixed, 850, 950)
    true_900 = band_energy(
        nk_.signal_filter(mixed, sampling_rate=4000, lowcut=10, highcut=400),
        850, 950)
    assumed_900 = band_energy(
        nk_.signal_filter(mixed, sampling_rate=1000, lowcut=10, highcut=400),
        850, 950)
    clean = nk_.emg_clean(mixed, sampling_rate=fs)
    amp_true = nk_.emg_amplitude(clean, sampling_rate=4000)
    amp_assumed = nk_.emg_amplitude(clean, sampling_rate=1000)
    amp_ratio = float(np.mean(amp_assumed) / np.mean(amp_true))
    url = "https://github.com/neuropsychology/NeuroKit/issues/1212"
    ok = (true_900 < raw_900 / 100.0 and assumed_900 > raw_900 * 0.5
          and amp_ratio > 2.0)
    return CheckResult(
        case="emg-filter-real-upstream", check="emg_filter", passed=ok,
        measured=f"900 Hz band energy raw={raw_900:.0f}, true fs={true_900:.0f} "
                 f"({true_900 / raw_900:.4f}x), assumed 1 kHz={assumed_900:.0f} "
                 f"({assumed_900 / raw_900:.2f}x); emg_amplitude mean "
                 f"true fs={float(np.mean(amp_true)):.3f} vs assumed "
                 f"{float(np.mean(amp_assumed)):.3f} ({amp_ratio:.2f}x)",
        expected="900 Hz attenuated >100x at the true fs, passes with the "
                 "assumed 1 kHz; amplitude differs >2x between the two calls",
        source_url=url,
        detail=(
            "REAL upstream filter is sampling-rate aware when given the "
            "true fs; the #1212 symptom (4x-shifted band) is reproduced by "
            "the caller's wrong fs assumption. Note: upstream's envelope "
            "band is (10, 400) Hz, not the fixture's (10, 500) Hz."
        ),
    )


# ---------------------------------------------------------------------------
# #1183 — signal power: REAL nk.signal_power vs the local trapezoid
# ---------------------------------------------------------------------------

def real_signal_power_agreement() -> CheckResult:
    """Real nk.signal_power vs this project's trapezoid on the same sine."""
    nk_ = _need_nk()
    import numpy as np

    fs = 100
    t = np.arange(0, 10, 1 / fs)
    sine = 2 * np.sin(2 * np.pi * 5 * t)
    real = nk_.signal_power(sine, frequency_band=[4, 6], sampling_rate=fs,
                            normalize=False)
    real_power = float(np.asarray(real).flat[0])
    local = signal_power([float(x) for x in sine], float(fs))
    rel = abs(real_power - local) / local if local else 1.0
    url = "https://github.com/neuropsychology/NeuroKit/issues/1183"
    return CheckResult(
        case="signal-power-real-upstream", check="signal_power",
        passed=rel <= 0.01,
        measured=f"real nk.signal_power {real_power:.4f} vs local trapezoid "
                 f"{local:.4f} (relative difference {rel:.2%})",
        expected="real and local power agree within 1% on the same A=2 sine",
        source_url=url,
        detail=(
            "real upstream power and the local trapezoid computation agree; "
            "no np.trapz is involved on either side"
        ),
    )


# ---------------------------------------------------------------------------
# Real record — MIT-BIH 100 excerpt via REAL wfdb + REAL nk.ecg_process
# ---------------------------------------------------------------------------

def real_ecg_record_excerpt() -> CheckResult:
    """Read the vendored MIT-BIH 100 excerpt with real wfdb, process it
    with real nk.ecg_process, and compare detected R-peaks against the
    excerpt's real annotations (within 100 ms)."""
    wfdb_ = _need_wfdb()
    nk_ = _need_nk()
    rec = wfdb_.rdrecord(str(DATA / "mitdb_100_10s"))
    ann = wfdb_.rdann(str(DATA / "mitdb_100_10s"), "atr")
    signal = rec.p_signal[:, 0]
    fs = int(rec.fs)
    _, info = nk_.ecg_process(signal, sampling_rate=fs)
    peaks = [int(p) for p in info["ECG_R_Peaks"]]
    annotated = [int(s) for s in ann.sample]
    window = int(fs * 0.1)  # 100 ms
    matched = sum(
        1 for a in annotated
        if peaks and min(abs(p - a) for p in peaks) <= window
    )
    heart_rate = 60.0 * len(peaks) / (len(signal) / fs)
    url = "https://physionet.org/content/mitdb/1.0.0/"
    ok = matched >= 10 and 60.0 <= heart_rate <= 100.0
    return CheckResult(
        case="ecg-record-real-upstream", check="ecg_record", passed=ok,
        measured=f"real ecg_process detected {len(peaks)} R-peaks; "
                 f"{matched}/{len(annotated)} annotated beats matched within "
                 f"100 ms; heart rate {heart_rate:.0f} bpm",
        expected="at least 10/14 annotated beats matched; heart rate 60-100 bpm",
        source_url=url,
        detail=(
            "REAL PhysioNet record (MIT-BIH 100, 10 s, MLII) read with real "
            "wfdb and processed with real neurokit2. Misses, recorded "
            "honestly: 2 annotated beats at the record edge (samples 18, "
            "77) and 1 offset by 133 ms (annotated 2044, detected 2092)."
        ),
    )


def run_all_real() -> list[CheckResult]:
    """Every real upstream check, in issue order."""
    results: list[CheckResult] = []
    results.append(real_rsp_short_crash())
    results.extend(real_rsp_phase_from_upstream())
    results.extend(real_rsa_crosscheck())
    results.append(real_dfa_invariance())
    results.append(real_emg_fs_awareness())
    results.append(real_signal_power_agreement())
    results.append(real_ecg_record_excerpt())
    return results
