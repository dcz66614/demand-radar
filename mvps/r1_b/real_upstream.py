# #1208 — DFA unit-invariance of the REAL nk.fractal_dfa
# ---------------------------------------------------------------------------

def real_dfa_invariance() -> CheckResult:
    """Real nk.fractal_dfa on the same signal at uV / mV / 1e-9 scales.

    nk.fractal_dfa returns (alpha, info); the PRD property is that alpha
    is the same within 1e-6 across amplitude units.
    """
    nk_ = _need_nk()
    import numpy as np

    rng = np.random.default_rng(42)
    sig = np.cumsum(rng.normal(0, 1, 512))
    alphas = {}
    for scale, name in ((1.0, "uV"), (1000.0, "mV"), (1e-9, "tiny")):
        result = nk_.fractal_dfa(sig * scale)
        alphas[name] = float(result[0] if isinstance(result, tuple) else result)
    spread = max(alphas.values()) - min(alphas.values())
    local = dfa_exponent([float(x) for x in sig])
    url = "https://github.com/neuropsychology/NeuroKit/issues/1208"
    return CheckResult(
        case="dfa-real-upstream-invariance", check="dfa",
        passed=all(math.isfinite(v) for v in alphas.values()) and spread <= 1e-6,
        measured=f"real fractal_dfa uV={alphas['uV']:.6f} mV={alphas['mV']:.6f} "
                 f"tiny={alphas['tiny']:.6f} (spread {spread:.2e}); "
                 f"local dfa_exponent {local:.4f} on the same signal",
        expected="same exponent within 1e-6 across amplitude units",
        source_url=url,
        detail=(
            "REAL upstream DFA is unit-invariant within 1e-6 (#1208 property "
            "holds in neurokit2 0.3.0); the local implementation gives a "
            "different value on the same signal (different box sizes), "
            "recorded here, not claimed as agreement"
        ),
    )


