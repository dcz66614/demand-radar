# #1242 — real rsp_process on an 8 s recording (still crashes upstream)
# ---------------------------------------------------------------------------

def real_rsp_short_crash() -> CheckResult:
    """Call REAL nk.rsp_process on an 8 s simulated RSP recording.

    Returns a failed CheckResult when the real library raises IndexError
    (the recorded #1242 crash, reproduced against neurokit2 0.3.0) and a
    passed one if it completes — the same detection semantics as
    signalcheck.check_rsp_short's buggy-path row.
    """
    nk_ = _need_nk()
    rsp = nk_.rsp_simulate(duration=8, sampling_rate=100, respiratory_rate=15,
                           random_state=42)
    url = "https://github.com/neuropsychology/NeuroKit/issues/1242"
    try:
        signals, info = nk_.rsp_process(rsp, sampling_rate=100)
        return CheckResult(
            case="rsp-short-real-upstream", check="rsp_short", passed=True,
            measured=f"real rsp_process completed on 8 s recording "
                     f"({len(info['RSP_Peaks'])} peaks)",
            expected="IndexError (the recorded #1242 crash) or clean completion",
            source_url=url,
            detail="real upstream handled the 8 s recording in this version",
        )
    except IndexError as exc:
        return CheckResult(
            case="rsp-short-real-upstream", check="rsp_short", passed=False,
            measured=f"real rsp_process raised IndexError on 8 s recording: {exc}",
            expected="completes without IndexError",
            source_url=url,
            detail="REAL upstream failure reproduced: neurokit2 0.3.0 "
                   "rsp_process still raises IndexError on an 8 s recording "
                   "(#1242 still live upstream); the guarded local path "
                   "handles the same signal without raising",
        )


