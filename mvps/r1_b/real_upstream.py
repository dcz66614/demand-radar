# #1196 — RSP phase durations from REAL upstream peaks
# ---------------------------------------------------------------------------

def _real_rsp_intervals():
    """(intervals in samples, fs) from real nk.rsp_process peaks/troughs."""
    nk_ = _need_nk()
    rsp = nk_.rsp_simulate(duration=60, sampling_rate=100, respiratory_rate=15,
                           random_state=42)
    _, info = nk_.rsp_process(rsp, sampling_rate=100)
    extrema = sorted(
        [(int(p), "peak") for p in info["RSP_Peaks"]]
        + [(int(t), "trough") for t in info["RSP_Troughs"]]
    )
    intervals = [
        [a, b] for (a, _), (b, _) in itertools.pairwise(extrema)
        if b > a
    ]
    return intervals, 100.0


def real_rsp_phase_from_upstream() -> list[CheckResult]:
    """Run the SAME check_rsp_phase on intervals from REAL upstream peaks.

    Correct durations (samples / fs) must pass; the seconds-as-samples
    error (durations 100x too small at fs=100) must fail — the #1196
    failure class, validated against real upstream output.
    """
    intervals, fs = _real_rsp_intervals()
    use = intervals[:4]
    expected = [(b - a) / fs for a, b in use]
    ok_row = check_rsp_phase(use, fs, expected, "samples")
    ok_row.case = "rsp-phase-real-upstream-correct"
    bad_row = check_rsp_phase(use, fs, [d / 100.0 for d in expected], "samples")
    bad_row.case = "rsp-phase-real-upstream-seconds-as-samples"
    return [ok_row, bad_row]


# ---------------------------------------------------------------------------
# #1230 — RSA cross-check against REAL nk.hrv_rsa
# ---------------------------------------------------------------------------

def real_rsa_crosscheck() -> list[CheckResult]:
    """Real nk.hrv_rsa Porges-Bohrer vs this project's rsa_from_period.

    Both are computed from the SAME RR periods (real nk.ecg_process
    peaks on a simulated ECG). The first row asserts cross-implementation
    agreement (same sign, delta < 1.0 ln(ms^2) — a loose bound, see the
    module docstring); the second asserts the rate-based error value is
    still flagged by check_rsa.
    """
    nk_ = _need_nk()
    ecg = nk_.ecg_simulate(duration=60, sampling_rate=1000, heart_rate=70,
                           random_state=42)
    signals, info = nk_.ecg_process(ecg, sampling_rate=1000)
    peaks = [int(p) for p in info["ECG_R_Peaks"]]
    period_ms = [float(b - a) for a, b in itertools.pairwise(peaks)]
    rsa = nk_.hrv_rsa(signals, sampling_rate=1000)
    real_rsa = float(rsa["RSA_PorgesBohrer"])
    local_rsa = rsa_from_period(period_ms)
    delta = abs(real_rsa - local_rsa)
    url = "https://github.com/neuropsychology/NeuroKit/issues/1230"
    rows = [CheckResult(
        case="rsa-real-upstream-crosscheck", check="rsa",
        passed=(math.isfinite(real_rsa) and math.isfinite(local_rsa)
                and (real_rsa >= 0) == (local_rsa >= 0)
                and delta <= RSA_CROSS_IMPL_TOL),
        measured=f"real Porges-Bohrer {real_rsa:.3f} ln(ms^2) vs local "
                 f"{local_rsa:.3f} ln(ms^2) (delta {delta:.3f})",
        expected="same sign, delta <= 1.0 ln(ms^2) (cross-implementation "
                 "bound, NOT the PRD 0.05 tolerance)",
        source_url=url,
        detail=(
            "real upstream RSA and the local computation agree in sign and "
            "order of magnitude on the same RR periods"
            if delta <= RSA_CROSS_IMPL_TOL else
            "real and local RSA differ by more than the cross-implementation "
            "bound — the two algorithms disagree on this data"
        ),
    )]
    rate_ms = [60000.0 / p for p in period_ms]  # the #1230 error: RSA on rate
    rate_rsa = rsa_from_period(rate_ms)
    flagged = check_rsa(period_ms, rate_rsa)
    flagged.case = "rsa-real-upstream-rate-value-flagged"
    rows.append(flagged)
    return rows


