try:
    import neurokit2 as nk
except ImportError:  # pragma: no cover - exercised only without the dep
    nk = None

try:
    import wfdb
except ImportError:  # pragma: no cover - exercised only without the dep
    wfdb = None

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"

# Cross-implementation agreement bound for RSA (ln(ms^2)). NOT the PRD's
# 0.05 tolerance: neurokit2's Porges-Bohrer and this project's moving-
# average detrend are different algorithms for the same quantity, so
# they agree in sign and order of magnitude, not to 0.05.
RSA_CROSS_IMPL_TOL = 1.0


def real_upstream_versions() -> dict:
    """Installed versions of the real upstream libraries (None if missing)."""
    out = {}
    for name, mod in (("neurokit2", nk), ("wfdb", wfdb)):
        out[name] = getattr(mod, "__version__", None) if mod is not None else None
    try:
        import numpy

        out["numpy"] = numpy.__version__
    except ImportError:
        out["numpy"] = None
    return out


def _need_nk():
    if nk is None:
        raise RuntimeError("neurokit2 is not installed: no real upstream path")
    return nk


def _need_wfdb():
    if wfdb is None:
        raise RuntimeError("wfdb is not installed: no real record path")
    return wfdb


